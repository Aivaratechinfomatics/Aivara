def build_deck(inputs: DeckInputs) -> io.BytesIO:
    """Builds the full deck in-memory: cover, TOC, executive summary, one
    slide per view (+ drivers), risk signals (if any), closing slide.

    Never writes to disk — returns a BytesIO the caller passes straight to
    st.download_button. Never calls the OpenRouter client — only reads from
    insight.cache.
    """
    prs = Presentation()
    prs.slide_width  = Inches(SLIDE_W)
    prs.slide_height = Inches(SLIDE_H)

    # Pre-count slides so footer can show "X / N"
    # Rough count: cover + toc + exec + views*2 (view+drivers) + risk + closing
    # We do two passes: first collect, then render.
    views = inputs.views

    # Build ordered slide list (view + optional drivers)
    view_slide_plan: list[tuple[str, object]] = []
    view_slide_plan.append(("cover", None))
    view_slide_plan.append(("toc",   None))
    view_slide_plan.append(("exec",  None))
    for v in views:
        view_slide_plan.append(("view",    v))
        if v.drivers_figure is not None or v.drivers_table:
            view_slide_plan.append(("drivers", v))
    if inputs.risk_signals:
        view_slide_plan.append(("risk",    None))
    view_slide_plan.append(("closing", None))

    total_slides = len(view_slide_plan)

    for slide_num, (kind, data) in enumerate(view_slide_plan, start=1):
        if kind == "cover":
            build_cover_slide(prs, inputs.dataset_name, inputs.period_covered, slide_num, total_slides)
        elif kind == "toc":
            build_toc_slide(prs, views, slide_num, total_slides)
        elif kind == "exec":
            build_executive_summary_slide(prs, views, slide_num, total_slides)
        elif kind == "view":
            build_view_slide(prs, data, slide_num, total_slides)
        elif kind == "drivers":
            build_drivers_slide(prs, data, slide_num, total_slides)
        elif kind == "risk":
            build_risk_signals_slide(prs, inputs.risk_signals, slide_num, total_slides)
        elif kind == "closing":
            build_closing_slide(prs, slide_num, total_slides)

    buffer = io.BytesIO()
    prs.save(buffer)
    buffer.seek(0)
    return buffer
