def build_cover_slide(prs: Presentation, dataset_name: str, period_covered: str, slide_number: int, total_slides: int) -> None:
    """Professional branded cover slide."""
    slide = _blank_slide(prs)

    # Bottom colour band (brand navy, ~40% of slide height)
    band_h = 3.10
    _add_rect(slide, 0, SLIDE_H - band_h, SLIDE_W, band_h, fill=COLOR_BRAND_NAVY)

    # Teal accent bar above the band
    _add_rect(slide, 0, SLIDE_H - band_h - 0.06, SLIDE_W, 0.06, fill=COLOR_BRAND_TEAL)

    # Logo text (replace with an actual logo image if available)
    _add_textbox(
        slide, "AIVARA",
        left=MARGIN_L, top=1.10,
        width=5.0, height=0.70,
        size=36, bold=True, color=COLOR_BRAND_NAVY,
    )
    _add_textbox(
        slide, "Insight  •  Lite",
        left=MARGIN_L, top=1.80,
        width=6.0, height=0.50,
        size=18, bold=False, color=COLOR_BRAND_TEAL,
    )

    # White text on the navy band
    _add_textbox(
        slide, dataset_name,
        left=MARGIN_L, top=SLIDE_H - band_h + 0.40,
        width=CONTENT_W, height=0.70,
        size=24, bold=True, color=COLOR_BG,
    )
    _add_textbox(
        slide, f"Period: {period_covered}",
        left=MARGIN_L, top=SLIDE_H - band_h + 1.15,
        width=CONTENT_W, height=0.45,
        size=14, color=RGBColor(0xCC, 0xD6, 0xEE),
    )
    generated_at = datetime.now(timezone.utc).strftime("%d %b %Y  %H:%M UTC")
    _add_textbox(
        slide, f"Generated  {generated_at}",
        left=MARGIN_L, top=SLIDE_H - band_h + 1.65,
        width=CONTENT_W, height=0.35,
        size=11, color=RGBColor(0x99, 0xAA, 0xCC),
    )

    _add_footer(slide, slide_number, total_slides)


def build_toc_slide(prs: Presentation, views: list[ViewExportData], slide_number: int, total_slides: int) -> None:
    """Auto-generated table of contents."""
    slide = _blank_slide(prs)
    _add_slide_title(slide, "Contents")

    col_count = 2
    col_w = CONTENT_W / col_count - 0.20
    items_per_col = max(1, (len(views) + col_count - 1) // col_count)

    for idx, view in enumerate(views):
        col = idx // items_per_col
        row = idx % items_per_col
        left = MARGIN_L + col * (col_w + 0.40)
        top  = CONTENT_TOP + 0.10 + row * 0.52

        # Bullet dot
        _add_rect(slide, left, top + 0.13, 0.09, 0.09, fill=COLOR_BRAND_TEAL)
        # View name
        _add_textbox(
            slide, view.view_name,
            left=left + 0.18, top=top,
            width=col_w - 0.20, height=0.45,
            size=13, color=COLOR_TEXT,
        )

    _add_footer(slide, slide_number, total_slides)


def build_section_divider_slide(prs: Presentation, section_name: str, slide_number: int, total_slides: int) -> None:
    """Full-bleed section divider."""
    slide = _blank_slide(prs)
    _add_rect(slide, 0, 0, SLIDE_W, SLIDE_H, fill=COLOR_BRAND_NAVY)
    # Teal accent stripe
    _add_rect(slide, 0, SLIDE_H / 2 - 0.06, SLIDE_W, 0.12, fill=COLOR_BRAND_TEAL)

    _add_textbox(
        slide, section_name,
        left=1.0, top=SLIDE_H / 2 - 1.10,
        width=SLIDE_W - 2.0, height=0.90,
        size=32, bold=True, color=COLOR_BG,
        align=PP_ALIGN.CENTER,
    )
    _add_footer(slide, slide_number, total_slides)


def build_executive_summary_slide(prs: Presentation, views: list[ViewExportData], slide_number: int, total_slides: int) -> None:
    slide = _blank_slide(prs)
    _add_slide_title(slide, "Executive Summary")

    # Gather up to 8 KPI tiles from all views
    all_tiles = [t for v in views for t in v.kpi_tiles][:8]
    tile_bottom = _render_kpi_tiles(slide, all_tiles, top=CONTENT_TOP)

    # Insight text below the tiles
    primary_insight = None
    for v in views:
        primary_insight = _cached_insight(v.view_name)
        if primary_insight:
            break

    if primary_insight:
        y = tile_bottom + 0.10
        if primary_insight.get("headline"):
            _add_textbox(
                slide, primary_insight["headline"],
                left=MARGIN_L, top=y,
                width=CONTENT_W, height=0.70,
                size=15, bold=True, color=COLOR_BRAND_NAVY,
            )
            y += 0.75
        if primary_insight.get("driver_explanation"):
            _add_textbox(
                slide, primary_insight["driver_explanation"],
                left=MARGIN_L, top=y,
                width=CONTENT_W, height=0.60,
                size=12, color=COLOR_TEXT,
            )

    _add_footer(slide, slide_number, total_slides)


def build_view_slide(prs: Presentation, view: ViewExportData, slide_number: int, total_slides: int) -> None:
    slide = _blank_slide(prs)
    _add_slide_title(slide, view.view_name)

    # KPI tiles
    tile_bottom = _render_kpi_tiles(slide, view.kpi_tiles, top=CONTENT_TOP)
    chart_top = tile_bottom

    # Available chart area
    avail_h = FOOTER_TOP - chart_top - 0.10

    insight = _cached_insight(view.view_name)

    if insight and view.trend_figure is not None:
        # Split layout: chart left, text panel right
        _place_chart(
            slide, view.trend_figure,
            left=MARGIN_L, top=chart_top,
            max_width=CHART_SPLIT_W, max_height=avail_h,
            render_width_px=HALF_WIDTH_PX, render_height_px=HALF_HEIGHT_PX,
        )
        # Text panel
        y = chart_top
        text_items = [
            (insight.get("headline"),          16, True,  COLOR_BRAND_NAVY),
            (insight.get("driver_explanation"), 12, False, COLOR_TEXT),
            ("Next: " + insight["suggested_action"] if insight.get("suggested_action") else None,
             12, True, COLOR_BRAND_TEAL),
        ]
        for text, size, bold, color in text_items:
            if text:
                h = 0.85 if bold else 0.75
                _add_textbox(
                    slide, text,
                    left=TEXT_PANEL_L, top=y,
                    width=TEXT_PANEL_W, height=h,
                    size=size, bold=bold, color=color,
                )
                y += h + 0.10

    elif view.trend_figure is not None:
        # Full-width chart
        _place_chart(
            slide, view.trend_figure,
            left=MARGIN_L, top=chart_top,
            max_width=CHART_FULL_W, max_height=avail_h,
            render_width_px=FULL_WIDTH_PX, render_height_px=FULL_HEIGHT_PX,
        )

    _add_footer(slide, slide_number, total_slides)


def build_drivers_slide(prs: Presentation, view: ViewExportData, slide_number: int, total_slides: int) -> None:
    if view.drivers_figure is None and not view.drivers_table:
        return
    slide = _blank_slide(prs)
    _add_slide_title(slide, f"Drivers — {view.view_name}")

    avail_h = FOOTER_TOP - CONTENT_TOP - 0.10

    if view.drivers_figure is not None:
        fig_w = CHART_SPLIT_W if view.drivers_table else CHART_FULL_W
        _place_chart(
            slide, view.drivers_figure,
            left=MARGIN_L, top=CONTENT_TOP,
            max_width=fig_w, max_height=avail_h,
        )

    if view.drivers_table:
        text_left = MARGIN_L + CHART_SPLIT_W + 0.20 if view.drivers_figure else MARGIN_L
        panel_w   = TEXT_PANEL_W if view.drivers_figure else CONTENT_W
        y = CONTENT_TOP
        _add_textbox(
            slide, "Top contributors",
            left=text_left, top=y, width=panel_w, height=0.45,
            size=14, bold=True, color=COLOR_BRAND_NAVY,
        )
        y += 0.50
        for row in view.drivers_table[:10]:
            category = row.get("category", "")
            pct = row.get("contribution_pct", 0)
            color = COLOR_ACCENT_POS if pct >= 0 else COLOR_ACCENT_NEG
            label = f"{category}:  {pct:+.1f}%"
            # Left accent bar
            bar_color = COLOR_ACCENT_POS if pct >= 0 else COLOR_ACCENT_NEG
            _add_rect(slide, text_left, y + 0.05, 0.05, 0.30, fill=bar_color)
            _add_textbox(
                slide, label,
                left=text_left + 0.12, top=y, width=panel_w - 0.15, height=0.38,
                size=12, color=color,
            )
            y += 0.42

    _add_footer(slide, slide_number, total_slides)


def build_risk_signals_slide(prs: Presentation, risk_signals: list[dict], slide_number: int, total_slides: int) -> None:
    if not risk_signals:
        return
    slide = _blank_slide(prs)
    _add_slide_title(slide, "Risk Signals")

    severity_colors = {
        "high":   COLOR_ACCENT_NEG,
        "medium": COLOR_ACCENT_WARN,
        "low":    COLOR_MUTED,
    }
    badge_bg_colors = {
        "high":   RGBColor(0xFC, 0xE8, 0xE8),
        "medium": RGBColor(0xFF, 0xF3, 0xCD),
        "low":    RGBColor(0xF0, 0xF4, 0xFB),
    }

    y = CONTENT_TOP + 0.05
    ROW_H = 0.58
    for signal in risk_signals[:10]:
        severity  = signal.get("severity", "low")
        text      = signal.get("description", "")
        s_color   = severity_colors.get(severity, COLOR_MUTED)
        bg_color  = badge_bg_colors.get(severity, COLOR_KPI_BG)

        # Background pill
        _add_rect(slide, MARGIN_L, y, CONTENT_W, ROW_H - 0.06, fill=bg_color, line=s_color, line_width_pt=0.5)
        # Left severity stripe
        _add_rect(slide, MARGIN_L, y, 0.10, ROW_H - 0.06, fill=s_color)
        # Badge label
        _add_textbox(
            slide, severity.upper(),
            left=MARGIN_L + 0.18, top=y + 0.05,
            width=0.80, height=ROW_H - 0.16,
            size=9, bold=True, color=s_color,
        )
        # Description
        _add_textbox(
            slide, text,
            left=MARGIN_L + 1.05, top=y + 0.05,
            width=CONTENT_W - 1.15, height=ROW_H - 0.16,
            size=12, color=COLOR_TEXT,
        )
        y += ROW_H

    _add_footer(slide, slide_number, total_slides)


def build_closing_slide(prs: Presentation, slide_number: int, total_slides: int) -> None:
    slide = _blank_slide(prs)

    # Navy top strip
    _add_rect(slide, 0, 0, SLIDE_W, 1.80, fill=COLOR_BRAND_NAVY)
    _add_rect(slide, 0, 1.80, SLIDE_W, 0.08, fill=COLOR_BRAND_TEAL)

