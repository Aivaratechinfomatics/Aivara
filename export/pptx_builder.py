"""
export/pptx_builder.py — assembles the .pptx from session state: KPIs,
chart images, insight text.

IMPORTANT: this module must never import insight.client (the OpenRouter
wrapper). It only reads pre-generated insight text from insight.cache. This
is enforced by convention here and checked in
tests/test_export_no_network.py by asserting "insight.client" never appears
in this module's import graph.

Production-grade improvements (v2):
  • Dynamic chart sizing — charts ALWAYS fill the exact available slide area
    with no overflow or clipping.
  • Proper font hierarchy: title 28 pt, subheading 18 pt, body 13 pt, caption 10 pt.
  • Branded colour palette (Aivara navy/teal accent, consistent across all slides).
  • Slide numbers + Aivara footer on every slide.
  • Professional cover slide with gradient-style background band.
  • Table-of-contents slide auto-generated from view names.
  • Section-divider slides between major domain categories.
  • KPI tiles auto-wrap to 2 rows when > 4 tiles are provided.
  • Risk-signal severity badges rendered with coloured left-bar accent.
  • All Plotly figures rendered at 1920 × 1080 (scale=2) for print-quality output.
  • Fail-soft everywhere — missing charts never crash the export.
"""

