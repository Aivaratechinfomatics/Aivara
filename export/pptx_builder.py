# ---------------------------------------------------------------------------
# Slide canvas constants — widescreen 16 : 9
# ---------------------------------------------------------------------------
SLIDE_W = 13.333   # inches
SLIDE_H = 7.5      # inches

MARGIN_L = 0.45    # left margin
MARGIN_R = 0.45    # right margin
MARGIN_T = 0.35    # top margin (below slide edge, not below title)
MARGIN_B = 0.40    # bottom margin (above slide edge — reserved for footer)

CONTENT_W = SLIDE_W - MARGIN_L - MARGIN_R      # 12.43"
TITLE_H   = 0.70                                # reserved for slide title row
FOOTER_H  = 0.30                                # footer strip height

# Y-coordinate where the title text box starts
TITLE_TOP = MARGIN_T
# Y-coordinate where content (KPIs / charts) can start
CONTENT_TOP = MARGIN_T + TITLE_H + 0.15
# Y-coordinate where footer starts
FOOTER_TOP = SLIDE_H - MARGIN_B - FOOTER_H

# Maximum chart area (no text panel beside it)
CHART_FULL_W = CONTENT_W
CHART_FULL_H = FOOTER_TOP - CONTENT_TOP - 0.10   # ≈ 5.50 inches

# Chart + text-panel split (chart on left, insight text on right)
TEXT_PANEL_W  = 3.80
CHART_SPLIT_W = CONTENT_W - TEXT_PANEL_W - 0.20   # ≈ 8.43"
TEXT_PANEL_L  = MARGIN_L + CHART_SPLIT_W + 0.20

# KPI tile constants
KPI_H          = 1.20   # tile height
KPI_GAP        = 0.18   # gap between tiles
KPI_MAX_ROW    = 4      # max tiles per row (wraps to second row otherwise)

# ---------------------------------------------------------------------------
# Brand colours — Aivara palette
# ---------------------------------------------------------------------------
COLOR_BG          = RGBColor(0xFF, 0xFF, 0xFF)
COLOR_BRAND_NAVY  = RGBColor(0x0D, 0x2B, 0x5C)   # primary brand deep navy
COLOR_BRAND_TEAL  = RGBColor(0x00, 0x8B, 0x8B)   # accent teal
COLOR_TEXT        = RGBColor(0x1A, 0x1A, 0x2E)   # near-black body text
COLOR_MUTED       = RGBColor(0x55, 0x5E, 0x75)   # secondary / captions
COLOR_ACCENT_POS  = RGBColor(0x0F, 0x7B, 0x3E)   # green — positive delta
COLOR_ACCENT_NEG  = RGBColor(0xC0, 0x2A, 0x2A)   # red — negative delta
COLOR_ACCENT_WARN = RGBColor(0xB8, 0x7A, 0x00)   # amber — medium severity
COLOR_KPI_BG      = RGBColor(0xF0, 0xF4, 0xFB)   # tile fill
COLOR_KPI_BORDER  = RGBColor(0xD0, 0xD8, 0xEE)   # tile border
COLOR_DIVIDER_BAR = RGBColor(0x00, 0x8B, 0x8B)   # section divider accent bar
COLOR_COVER_BAND  = RGBColor(0x0D, 0x2B, 0x5C)   # cover-slide bottom band

FOOTNOTE_TEXT = (
    "Generated by Aivara Insight  •  All figures computed locally from the "
    "uploaded dataset  •  AI narrative enrichment via OpenRouter (offline fallback available)"
)

