def _blank_slide(prs: Presentation):
    blank_layout = prs.slide_layouts[6]
    return prs.slides.add_slide(blank_layout)


def _inches(val: float) -> int:
    """Convert float inches to EMU."""
    return Inches(val)


def _fill_slide_background(slide, color: RGBColor) -> None:
    background = slide.background
    fill = background.fill
    fill.solid()
    fill.fore_color.rgb = color


def _add_rect(slide, left: float, top: float, width: float, height: float,
              fill: RGBColor | None = None, line: RGBColor | None = None,
              line_width_pt: float = 0.75):
    """Add a filled rectangle shape (MSO_SHAPE_TYPE 1 = RECTANGLE)."""
    shape = slide.shapes.add_shape(
        1, Inches(left), Inches(top), Inches(width), Inches(height)
    )
    if fill:
        shape.fill.solid()
        shape.fill.fore_color.rgb = fill
    else:
        shape.fill.background()
    if line:
        shape.line.color.rgb = line
        shape.line.width = Pt(line_width_pt)
    else:
        shape.line.fill.background()
    return shape


def _add_textbox(
    slide,
    text: str,
    left: float,
    top: float,
    width: float,
    height: float,
    size: int = 13,
    bold: bool = False,
    color: RGBColor = None,
    align: PP_ALIGN = PP_ALIGN.LEFT,
    word_wrap: bool = True,
) -> None:
    """Generic textbox factory."""
    if color is None:
        color = COLOR_TEXT
    box = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width), Inches(height))
    tf = box.text_frame
    tf.word_wrap = word_wrap
    para = tf.paragraphs[0]
    para.alignment = align
    run = para.add_run()
    run.text = text
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    return box


def _add_footer(slide, slide_number: int, total_slides: int) -> None:
    """Render a consistent bottom footer strip on every slide."""
    # Subtle separator line
    _add_rect(slide, MARGIN_L, FOOTER_TOP - 0.03, CONTENT_W, 0.03, fill=COLOR_KPI_BORDER)
    # Brand name on left
    _add_textbox(
        slide, "Aivara Insight",
        left=MARGIN_L, top=FOOTER_TOP + 0.03,
        width=4.0, height=FOOTER_H - 0.06,
        size=9, color=COLOR_MUTED,
    )
    # Slide number on right
    _add_textbox(
        slide, f"{slide_number} / {total_slides}",
        left=SLIDE_W - MARGIN_R - 1.5, top=FOOTER_TOP + 0.03,
        width=1.5, height=FOOTER_H - 0.06,
        size=9, color=COLOR_MUTED, align=PP_ALIGN.RIGHT,
    )


def _add_slide_title(slide, text: str) -> None:
    """Slide title with bottom accent underline."""
    _add_textbox(
        slide, text,
        left=MARGIN_L, top=TITLE_TOP,
        width=CONTENT_W, height=TITLE_H,
        size=22, bold=True, color=COLOR_BRAND_NAVY,
    )
    # Thin accent line under the title
    _add_rect(slide, MARGIN_L, TITLE_TOP + TITLE_H, CONTENT_W, 0.04, fill=COLOR_BRAND_TEAL)


# ---------------------------------------------------------------------------
# KPI tile renderer
# ---------------------------------------------------------------------------

def _render_kpi_tiles(
    slide,
    tiles: list[KPITileData],
    top: float,
) -> float:
    """
    Render up to 8 KPI tiles in one or two rows.
    Returns the Y-coordinate immediately after the last tile row.
    """
    if not tiles:
        return top

    tiles = tiles[:8]
    row1 = tiles[:KPI_MAX_ROW]
    row2 = tiles[KPI_MAX_ROW:]

    def _render_row(row: list[KPITileData], row_top: float):
        n = len(row)
        available = CONTENT_W
        tile_w = min(2.80, (available - KPI_GAP * (n - 1)) / n)
        for i, tile in enumerate(row):
            left = MARGIN_L + i * (tile_w + KPI_GAP)
            shape = _add_rect(
                slide, left, row_top, tile_w, KPI_H,
                fill=COLOR_KPI_BG, line=COLOR_KPI_BORDER, line_width_pt=0.5,
            )
            tf = shape.text_frame
            tf.word_wrap = True
            tf.margin_left = Emu(60960)    # 0.85mm
            tf.margin_top  = Emu(36288)    # 0.5mm

            # Label row
            p_label = tf.paragraphs[0]
            r_label = p_label.add_run()
            r_label.text = tile.label
            r_label.font.size = Pt(10)
            r_label.font.color.rgb = COLOR_MUTED

            # Value row
            p_value = tf.add_paragraph()
            r_value = p_value.add_run()
            r_value.text = tile.value_display
            r_value.font.size = Pt(20)
            r_value.font.bold = True
            r_value.font.color.rgb = COLOR_BRAND_NAVY

            # Delta row
            if tile.delta_display:
                p_delta = tf.add_paragraph()
                r_delta = p_delta.add_run()
                r_delta.text = tile.delta_display
                r_delta.font.size = Pt(11)
                r_delta.font.bold = True
                r_delta.font.color.rgb = (
                    COLOR_ACCENT_POS if tile.delta_positive
                    else COLOR_ACCENT_NEG
                ) if tile.delta_positive is not None else COLOR_MUTED

    _render_row(row1, top)
    bottom = top + KPI_H
    if row2:
        _render_row(row2, top + KPI_H + KPI_GAP)
        bottom = top + 2 * KPI_H + KPI_GAP

    return bottom + 0.20   # small padding below last row


# ---------------------------------------------------------------------------
# Chart placement helper — the core of the fix
# ---------------------------------------------------------------------------

def _place_chart(
    slide,
    fig,
    left: float,
    top: float,
    max_width: float,
    max_height: float,
    render_width_px: int = FULL_WIDTH_PX,
    render_height_px: int = FULL_HEIGHT_PX,
) -> None:
    """
    Render *fig* and place it on *slide* so it fits within the bounding
    box defined by (left, top, max_width, max_height) without overflow.

    Strategy:
      1. Render the chart to PNG at a fixed high resolution.
      2. Compute the aspect ratio of the rendered PNG.
      3. Scale it to fill max_width while capping at max_height.
         If max_height is the binding constraint, scale from that side.
      4. Centre the image vertically within the available area.
    """
    try:
        stream = figure_to_png_stream(
            fig, width=render_width_px, height=render_height_px
        )
    except Exception:
        return   # fail soft — never crash the export

    aspect = render_width_px / render_height_px  # e.g. 1920/1080 ≈ 1.778

    # Try width-first
    img_w = max_width
    img_h = img_w / aspect

    # If that would overflow the height budget, fit to height instead
    if img_h > max_height:
        img_h = max_height
        img_w = img_h * aspect

    # Horizontal centering within max_width
    img_left = left + (max_width - img_w) / 2.0
    # Vertical centering within max_height
    img_top  = top  + (max_height - img_h) / 2.0

    try:
        slide.shapes.add_picture(
            stream,
            Inches(img_left),
            Inches(img_top),
            width=Inches(img_w),
            height=Inches(img_h),
        )
    except Exception:
        pass   # defensive — never crash


